"""Strategy datasets on disk, with provenance and license on every file.

``data/preflop/pushfold/<n>max_<depth>bb.json`` holds the compact strategy
an agent reads. A cell (infoset x hand class) that the solver visited fewer
than ``min_visits`` times is stored as null: rarely reached, not converged,
so no number is claimed for it.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .base import SolveResult
from .hands import CLASS_NAMES

REPO = Path(__file__).resolve().parents[2]
PUSHFOLD_DIR = REPO / "data" / "preflop" / "pushfold"
DATASET = "pushfold-chipev"
VERSION = "1"
LICENSE = ("Generated by this repository's own solver; contains no third-party data. "
           "Covered by the repository's license.")
SOLVER_NAME = "PushFoldSolver: external-sampling linear MCCFR, synchronous parallel batches"


def file_name(players: int, stack_bb: float) -> str:
    return f"{players}max_{stack_bb:g}bb.json"


def compact(result: SolveResult, min_visits: int = 200) -> dict[str, Any]:
    strategy = {}
    for name, cell in result.strategy.items():
        strategy[name] = {
            "actions": cell["actions"],
            "aggress_prob": [p if v >= min_visits else None
                             for p, v in zip(cell["aggress_prob"], cell["visits"])],
        }
    return {
        "dataset": DATASET,
        "version": VERSION,
        "strategy_source": str(result.strategy_source),
        "solver": SOLVER_NAME,
        "license": LICENSE,
        "game": result.request.params,
        "solver_config": result.request.solver,
        "request_hash": result.request.key(),
        "iterations": result.iterations,
        "convergence": result.convergence,
        "notes": result.notes,
        "min_visits": min_visits,
        "classes": list(CLASS_NAMES),
        "strategy": strategy,
    }


def write(result: SolveResult, out_dir: Path = PUSHFOLD_DIR, min_visits: int = 200) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    data = compact(result, min_visits)
    path = out_dir / file_name(int(data["game"]["players"]), float(data["game"]["stack_bb"]))
    path.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    return path


def load_all(directory: Path = PUSHFOLD_DIR) -> dict[tuple[int, float], dict[str, Any]]:
    """{(players, stack_bb): dataset} for every file in the directory."""
    out = {}
    for path in sorted(directory.glob("*max_*bb.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        out[(int(data["game"]["players"]), float(data["game"]["stack_bb"]))] = data
    return out


def record(db_url: str, result: SolveResult, path: Path) -> None:
    """Register the dataset and cache the full result in the database."""
    from backend.db import GtoDataset, SolverResultRow, make_engine, make_sessionmaker, upgrade

    upgrade(db_url)
    data = compact(result)
    rows = sum(sum(p is not None for p in c["aggress_prob"]) for c in data["strategy"].values())
    with make_sessionmaker(make_engine(db_url))() as db:
        db.add(GtoDataset(
            name=f"{DATASET}/{path.stem}", version=VERSION, source=str(result.strategy_source),
            license=LICENSE, row_count=rows, path=str(path.relative_to(REPO) if path.is_relative_to(REPO) else path),
            details={"game": result.request.params, "solver": SOLVER_NAME,
                     "solver_config": result.request.solver, "convergence": result.convergence},
        ))
        key = result.request.key()
        old = db.query(SolverResultRow).filter_by(request_hash=key).one_or_none()
        if old is not None:
            db.delete(old)
            db.flush()
        db.add(SolverResultRow(
            request_hash=key, config={"game": result.request.game, **result.request.params,
                                      "solver": result.request.solver},
            iterations=result.iterations,
            exploitability=result.convergence.get("nash_conv_upper_bb"),
            result=result.to_json(), source=str(result.strategy_source),
        ))
        db.commit()
