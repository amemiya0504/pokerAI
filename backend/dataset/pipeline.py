"""GTO dataset pipeline (Milestone 6): solve spots, extract rows, write shards.

Layout of ``<out>/``:

* ``manifest.json``: what the dataset is (config, generator, provenance).
  Resuming requires the same config; a different one is refused.
* ``shard-00000.parquet`` ...: one file per ``shard_size`` spots, written to
  a temporary name and renamed when complete, so an interrupted run leaves
  no half-written shard. A restart skips every complete shard.

One row = one first-street decision node of one solved spot: both players'
reach over the 1,326 combos (float16), the actor's action probabilities
(float16) and per-combo action EVs in chips (float32, NaN where undefined).
"""

from __future__ import annotations

import json
import os
import time
from collections.abc import Callable
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from backend.agents.base import StrategySource
from backend.engine.cards import parse_cards

from .spots import DEFAULT_TREES, Spot, TreeSpec, make_spot, tree_config

FORMAT = "poker-ai-gto-dataset/1"
LICENSE = ("Generated by this repository's own solver from synthetic spots; contains no "
           "third-party data. Covered by the repository's license.")


@dataclass(frozen=True)
class DatasetConfig:
    name: str
    version: str
    seed: int
    spots: int
    shard_size: int = 50
    streets: dict[str, float] = field(default_factory=lambda: {"river": 0.7, "turn": 0.3})
    trees: dict[str, TreeSpec] = field(default_factory=lambda: dict(DEFAULT_TREES))
    target_pct_pot: float = 0.5  # stop solving at this exploitability
    max_iterations: int = 600
    check_every: int = 50
    variant: str = "dcfr"

    def to_json(self) -> dict[str, Any]:
        d = asdict(self)
        d["trees"] = {k: asdict(v) for k, v in self.trees.items()}
        return d

    @classmethod
    def from_json(cls, d: dict[str, Any]) -> DatasetConfig:
        d = dict(d)
        d["trees"] = {k: TreeSpec(**v) for k, v in d["trees"].items()}
        return cls(**d)

    @property
    def n_shards(self) -> int:
        return -(-self.spots // self.shard_size)


def shard_path(out: Path, k: int) -> Path:
    return out / f"shard-{k:05d}.parquet"


def solve_spot(spot: Spot, cfg: DatasetConfig, device: str | None = None, dtype=None):
    """Solve one spot; returns (rows, convergence)."""
    import torch

    from backend.solver.subgame_gpu import BatchedSubgameCFR

    cfr = BatchedSubgameCFR(parse_cards(spot.board), spot.ranges(), tree_config(spot, cfg.trees),
                            cfg.variant, device=device, dtype=dtype or torch.float32)
    done, ex = 0, None
    while done < cfg.max_iterations:
        step = min(cfg.check_every, cfg.max_iterations - done)
        cfr.iterate(step)
        done += step
        ex = cfr.exploitability()
        if ex["exploitability_pct_pot"] <= cfg.target_pct_pot:
            break
    conv = {"iterations": done, **ex}
    rows = cfr.node_table()
    cfr.release()  # free GPU memory and the CUDA graph before the next spot is captured
    return rows, conv


def _table(spot: Spot, rows: list[dict], conv: dict):
    import pyarrow as pa

    f16 = pa.list_(pa.float16())
    out = {
        "spot": pa.array([spot.index] * len(rows), pa.int32()),
        "street": pa.array([spot.street] * len(rows), pa.string()),
        "board": pa.array([spot.board] * len(rows), pa.string()),
        "pot": pa.array([spot.pot] * len(rows), pa.float32()),
        "stack": pa.array([spot.stack] * len(rows), pa.float32()),
        "path": pa.array([r["path"] for r in rows], pa.string()),
        "player": pa.array([r["player"] for r in rows], pa.int8()),
        "actions": pa.array([r["actions"] for r in rows], pa.list_(pa.string())),
        "inv_oop": pa.array([r["inv"][0] for r in rows], pa.float32()),
        "inv_ip": pa.array([r["inv"][1] for r in rows], pa.float32()),
        "reach_oop": pa.array([r["reach"][0].astype(np.float16) for r in rows], f16),
        "reach_ip": pa.array([r["reach"][1].astype(np.float16) for r in rows], f16),
        "strategy": pa.array([r["strategy"].astype(np.float16).ravel() for r in rows], f16),
        "ev": pa.array([r["ev"].astype(np.float32).ravel() for r in rows], pa.list_(pa.float32())),
        "iterations": pa.array([conv["iterations"]] * len(rows), pa.int32()),
        "exploitability_pct_pot": pa.array([conv["exploitability_pct_pot"]] * len(rows), pa.float32()),
    }
    return pa.table(out)


def manifest(cfg: DatasetConfig, commit: str | None) -> dict[str, Any]:
    return {
        "format": FORMAT,
        "dataset": cfg.name,
        "version": cfg.version,
        "strategy_source": str(StrategySource.SOLVER_APPROX),
        "license": LICENSE,
        "git_commit": commit,
        "config": cfg.to_json(),
        "notes": [
            "Heads-up postflop spots (turn/river) with an abstracted bet tree, solved by "
            "BatchedSubgameCFR until exploitability <= target_pct_pot or max_iterations.",
            "Ranges are synthetic (top-X% by the Chen formula), not from a preflop equilibrium.",
            "One row per first-street decision node; EVs in chips with the starting pot split evenly.",
        ],
    }


def run(cfg: DatasetConfig, out: Path, device: str | None = None,
        progress: Callable[[int, int, float], None] | None = None,
        stop_after: int | None = None) -> dict[str, Any]:
    """Build (or resume) the dataset. ``stop_after`` simulates an interruption
    after that many spots in this call (used by tests)."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    from backend.arena.storage import git_commit

    out.mkdir(parents=True, exist_ok=True)
    mpath = out / "manifest.json"
    if mpath.exists():
        old = json.loads(mpath.read_text(encoding="utf-8"))
        if old["config"] != cfg.to_json():
            raise ValueError(f"{out} holds a dataset with a different config; refusing to mix them")
    else:
        mpath.write_text(json.dumps(manifest(cfg, git_commit()), ensure_ascii=False, indent=2),
                         encoding="utf-8")
    for tmp in out.glob(".*.tmp"):
        tmp.unlink()  # leftovers of an interrupted shard

    solved = 0
    t0 = time.perf_counter()
    for k in range(cfg.n_shards):
        path = shard_path(out, k)
        if path.exists():
            continue
        tables = []
        for i in range(k * cfg.shard_size, min((k + 1) * cfg.shard_size, cfg.spots)):
            if stop_after is not None and solved >= stop_after:
                raise KeyboardInterrupt(f"stopped after {solved} spots (simulated interruption)")
            spot = make_spot(cfg.seed, i, cfg.streets)
            rows, conv = solve_spot(spot, cfg, device)
            tables.append(_table(spot, rows, conv))
            solved += 1
            if progress:
                progress(i + 1, cfg.spots, time.perf_counter() - t0)
        tmp = out / f".{path.name}.tmp"
        pq.write_table(pa.concat_tables(tables), tmp)
        os.replace(tmp, path)  # atomic: a shard exists only when complete
    return {"solved_now": solved, "seconds": time.perf_counter() - t0,
            "shards": sorted(p.name for p in out.glob("shard-*.parquet"))}


def register(db_url: str, out: Path, report: dict[str, Any]) -> None:
    """Record a validated dataset in ``gto_datasets``."""
    from backend.db import GtoDataset, make_engine, make_sessionmaker, upgrade

    m = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
    upgrade(db_url)
    with make_sessionmaker(make_engine(db_url))() as db:
        db.add(GtoDataset(name=m["dataset"], version=m["version"], source=m["strategy_source"],
                          license=m["license"], row_count=report["rows"], path=str(out),
                          details={"config": m["config"], "git_commit": m["git_commit"],
                                   "validation": {k: v for k, v in report.items() if k != "errors"}}))
        db.commit()
